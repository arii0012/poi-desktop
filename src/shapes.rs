/// Генерация точек фигуры (для отрисовки и depth)
pub struct ShapeMesh {
    pub points: Vec<[f32; 2]>,   // нормализованные 0..1
    pub depth: Vec<f32>,
}

pub fn generate_mesh(shape: usize, variant: usize, density: usize) -> ShapeMesh {
    let mut points = Vec::with_capacity(density * 2);
    let mut depth = Vec::with_capacity(density * 2);

    // небольшое смещение от варианта
    let ox = ((variant % 3) as f32 - 1.0) * 0.03;
    let oy = (((variant / 3) % 3) as f32 - 1.0) * 0.02;

    let n = density.max(80);

    match shape {
        1 => { // Шар
            for i in 0..n {
                let a = i as f32 / n as f32 * PI * 2.0;
                let r = 0.42;
                points.push([0.5 + r * a.cos() + ox, 0.5 + r * a.sin() + oy]);
                depth.push(0.9);
            }
            // внутренние кольца
            for ring in 1..4 {
                let rr = 0.42 * (1.0 - ring as f32 * 0.22);
                for i in 0..(n/2) {
                    let a = i as f32 / (n/2) as f32 * PI * 2.0;
                    points.push([0.5 + rr * a.cos() + ox, 0.5 + rr * a.sin() + oy]);
                    depth.push(0.5 - ring as f32 * 0.1);
                }
            }
        }
        2 => { // Сердце
            for i in 0..n {
                let t = i as f32 / n as f32 * PI * 2.0;
                let x = 16.0 * t.sin().powi(3);
                let y = -(13.0 * t.cos() - 5.0 * (2.0*t).cos() - 2.0 * (3.0*t).cos() - (4.0*t).cos());
                points.push([0.5 + x * 0.028 + ox, 0.48 + y * 0.028 + oy]);
                depth.push(0.85);
            }
        }
        3 | 30 => { // Звезда
            let rays = if variant % 2 == 0 { 5 } else { 8 };
            for i in 0..(rays * 2) {
                let a = -PI / 2.0 + i as f32 * PI / rays as f32;
                let r = if i % 2 == 0 { 0.45 } else { 0.20 };
                points.push([0.5 + r * a.cos() + ox, 0.5 + r * a.sin() + oy]);
                depth.push(if i % 2 == 0 { 0.9 } else { 0.5 });
            }
        }
        15 | 26 => { // Планета + кольца
            for i in 0..n {
                let a = i as f32 / n as f32 * PI * 2.0;
                points.push([0.5 + 0.32 * a.cos() + ox, 0.5 + 0.32 * a.sin() + oy]);
                depth.push(0.9);
            }
            // кольца (Сатурн и т.п.)
            let rings = if variant >= 3 { 3 } else { 1 };
            for r in 0..rings {
                let rr = 0.42 + r as f32 * 0.08;
                for i in 0..(n/2) {
                    let a = i as f32 / (n/2) as f32 * PI * 2.0;
                    // эллипс
                    points.push([0.5 + rr * a.cos() + ox, 0.5 + rr * 0.35 * a.sin() + oy]);
                    depth.push(0.4 - r as f32 * 0.08);
                }
            }
            if variant == 5 { // чёрная дыра — больше спирали
                for i in 0..n {
                    let t = i as f32 / n as f32;
                    let a = t * PI * 6.0;
                    let r = 0.15 + t * 0.35;
                    points.push([0.5 + r * a.cos() + ox, 0.5 + r * a.sin() + oy]);
                    depth.push(0.3 + t * 0.5);
                }
            }
        }
        17 | 27 => { // Ракета
            let body = [
                [0.5, 0.08], [0.62, 0.28], [0.62, 0.65], [0.5, 0.92],
                [0.38, 0.65], [0.38, 0.28],
            ];
            for p in &body {
                points.push([p[0] + ox, p[1] + oy]);
                depth.push(0.85);
            }
            // плавники
            points.push([0.38 + ox, 0.62 + oy]); points.push([0.25 + ox, 0.82 + oy]); points.push([0.38 + ox, 0.72 + oy]);
            points.push([0.62 + ox, 0.62 + oy]); points.push([0.75 + ox, 0.82 + oy]); points.push([0.62 + ox, 0.72 + oy]);
            depth.extend([0.6, 0.6, 0.6, 0.6, 0.6, 0.6]);
            // огонь
            if variant > 0 {
                for i in 0..12 {
                    let t = i as f32 / 12.0;
                    points.push([0.5 + (t - 0.5) * 0.15 + ox, 0.92 + t * 0.12 + oy]);
                    depth.push(0.4);
                }
            }
        }
        19 => { // Писюн
            for i in 0..20 {
                let t = i as f32 / 19.0;
                points.push([0.42 + ox, 0.15 + t * 0.55 + oy]);
                points.push([0.58 + ox, 0.15 + t * 0.55 + oy]);
                depth.push(0.8); depth.push(0.8);
            }
            // головка
            for i in 0..16 {
                let a = i as f32 / 16.0 * PI * 2.0;
                points.push([0.5 + 0.12 * a.cos() + ox, 0.72 + 0.12 * a.sin() + oy]);
                depth.push(0.95);
            }
            // яйца
            for i in 0..12 {
                let a = i as f32 / 12.0 * PI * 2.0;
                points.push([0.38 + 0.10 * a.cos() + ox, 0.82 + 0.09 * a.sin() + oy]);
                points.push([0.62 + 0.10 * a.cos() + ox, 0.82 + 0.09 * a.sin() + oy]);
                depth.push(0.7); depth.push(0.7);
            }
        }
        20 => { // Сиська
            for side in [-1.0f32, 1.0] {
                for i in 0..24 {
                    let a = i as f32 / 24.0 * PI * 2.0;
                    points.push([0.5 + side * 0.18 + 0.16 * a.cos() + ox, 0.52 + 0.16 * a.sin() + oy]);
                    depth.push(0.9);
                }
                // сосок
                for i in 0..8 {
                    let a = i as f32 / 8.0 * PI * 2.0;
                    points.push([0.5 + side * 0.18 + 0.04 * a.cos() + ox, 0.52 + 0.04 * a.sin() + oy]);
                    depth.push(0.5);
                }
            }
        }
        21 => { // НЛО
            for i in 0..n {
                let a = i as f32 / n as f32 * PI * 2.0;
                points.push([0.5 + 0.38 * a.cos() + ox, 0.48 + 0.12 * a.sin() + oy]);
                depth.push(0.85);
            }
            for i in 0..(n/2) {
                let a = i as f32 / (n/2) as f32 * PI * 2.0;
                points.push([0.5 + 0.22 * a.cos() + ox, 0.42 + 0.10 * a.sin() + oy]);
                depth.push(0.7);
            }
            // лучи
            for lx in [-0.2f32, 0.0, 0.2] {
                points.push([0.5 + lx + ox, 0.58 + oy]);
                points.push([0.5 + lx * 1.4 + ox, 0.92 + oy]);
                depth.push(0.4); depth.push(0.2);
            }
        }
        23 => { // Котик
            for i in 0..n {
                let a = i as f32 / n as f32 * PI * 2.0;
                points.push([0.5 + 0.32 * a.cos() + ox, 0.55 + 0.32 * a.sin() + oy]);
                depth.push(0.85);
            }
            // уши
            points.push([0.32 + ox, 0.35 + oy]); points.push([0.28 + ox, 0.12 + oy]); points.push([0.42 + ox, 0.35 + oy]);
            points.push([0.68 + ox, 0.35 + oy]); points.push([0.72 + ox, 0.12 + oy]); points.push([0.58 + ox, 0.35 + oy]);
            depth.extend([0.7, 0.7, 0.7, 0.7, 0.7, 0.7]);
        }
        _ => { // fallback — круг / капюшон
            for i in 0..n {
                let a = i as f32 / n as f32 * PI * 2.0;
                points.push([0.5 + 0.38 * a.cos() + ox, 0.55 + 0.38 * a.sin() + oy]);
                depth.push(0.8);
            }
        }
    }

    ShapeMesh { points, depth }
}
